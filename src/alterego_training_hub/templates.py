def list_templates() -> list[TemplateInfo]:
    return [
        TemplateInfo(template_id, meta["title"], meta["description"])
        for template_id, meta in TEMPLATES.items()
    ]


def create_project(workspace: str | Path, project_name: str,
                   template_id: str = "minimal-lm") -> list[str]:
    root = Path(workspace).expanduser().resolve()
    if not root.is_dir():
        raise TemplateError(f"Рабочая папка не найдена: {root}")
    name = str(project_name).strip()
    if not _PROJECT_NAME_RE.fullmatch(name):
        raise TemplateError(
            "Имя проекта: латиница, цифры, дефис/подчёркивание, 1–40 символов.")
    if template_id not in TEMPLATES:
        raise TemplateError(f"Неизвестный шаблон: {template_id}")
    target = root / name
    if target.exists():
        raise TemplateError(f"Папка уже существует: {target}")

    config = dict(DEFAULT_CONFIG)
    if template_id == "sft-chat":
        config["model"] = "sft-chat-scaffold"
        config["epochs"] = 3

    files: dict[str, str] = {
        "config.json": json.dumps(config, ensure_ascii=False, indent=2) + "\n",
        "README.md": _README_MD.format(name=name),
        "data/README.md": _DATA_README,
    }
    if template_id == "minimal-lm":
        files["train.py"] = _TRAIN_PY
        files["eval.py"] = _EVAL_PY
    else:
        files["train.py"] = _SFT_TRAIN_PY
        files["eval.py"] = _EVAL_PY

    created: list[str] = []
    for rel, content in files.items():
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(rel)
    return sorted(created)


def load_config(path: str | Path) -> dict:
    config_path = Path(path).expanduser()
    if config_path.is_dir():
        config_path = config_path / "config.json"
    if not config_path.is_file():
        raise TemplateError(f"config.json не найден: {config_path}")
    try:
        raw = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        raise TemplateError("config.json повреждён.") from None
    if not isinstance(raw, dict):
        raise TemplateError("config.json должен быть объектом JSON.")
    return raw


def save_config(path: str | Path, config: dict) -> Path:
    if not isinstance(config, dict):
        raise TemplateError("Конфигурация должна быть объектом.")
    config_path = Path(path).expanduser()
    if config_path.is_dir():
        config_path = config_path / "config.json"
    for key in ("lr", "epochs", "batch_size", "seed"):
        if key in config:
            try:
                float(config[key])
            except (TypeError, ValueError):
                raise TemplateError(f"Параметр {key} должен быть числом.") from None
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(json.dumps(config, ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
    return config_path
